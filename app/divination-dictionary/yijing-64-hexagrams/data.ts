function buildLines(summary: string) {
  return [
    `初爻: ${summary}の始まりです。まだ外へ大きく出るより、足元を確かめる段階です。`,
    `二爻: 内側の姿勢が整い始めます。信頼できる支えを作り、焦らず形を安定させます。`,
    `三爻: 迷い、抵抗、過剰反応が出やすい位置です。卦の主題を乱暴に扱うと問題が表面化します。`,
    `四爻: 外へ出る直前の調整です。相手や環境との距離を測る必要があります。`,
    `五爻: 判断の中心です。ここで卦の主題をどう使うかが問われます。`,
    `上爻: 行き過ぎと終局を読みます。次の卦へ移る前に、何を残し何を手放すかを見ます。`,
  ];
}

export const yijingHexagrams: YijingHexagram[] = seed.map((item, index) => {
  const number = index + 1;
  const [slug, name, reading, summary, keywords] = item;
  return {
    number,
    slug,
    name,
    reading,
    summary,
    keywords: [...keywords],
    detail: `${name}は「${summary}」を主題に持つ卦です。易経では、現在の状況をひとつの固定した答えとしてではなく、変化の途中にある姿として読みます。この卦が出たときは、何が強まり、何が弱まり、どこで態度を整えるべきかを見ます。`,
    love: `恋愛や人間関係では、${summary}という流れが関係にどう現れているかを読みます。相手を動かすことより、自分の態度、距離感、言葉の置き方を整えることが大切です。`,
    work: `仕事では、${summary}というテーマが計画、交渉、人間関係、タイミングに出ます。急ぐべきか、整えるべきか、退くべきかを爻の位置と合わせて判断します。`,
    lines: buildLines(summary),
    changingHexagram: "変卦は、現在の卦がどの方向へ移ろうとしているかを見るための補助線です。一爻だけが動く場合はその爻を重く読み、複数爻が動く場合は下から上へ変化の流れを追います。変爻が多いほど、状況の入れ替わりは大きくなります。",
  };
});

export function getYijingHexagram(slug: string) {
  return yijingHexagrams.find((item) => item.slug === slug);
}
